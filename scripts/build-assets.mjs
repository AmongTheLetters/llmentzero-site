// Builds dist/ (the Workers static-assets directory) from the public site files.
// Uses an ALLOWLIST so source code, migrations, tests and node_modules are never published.
// Also records the version and SHA-256 of each legal document exactly as published,
// for the clickwrap acceptance log (src/generated/legal.js).
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const dist = join(root, "dist");
const allowFiles = ["robots.txt", "sitemap.xml", "favicon.ico", "site.webmanifest", "LICENSE", "THIRD-PARTY-NOTICES.md"];
const allowDirs = ["assets", ".well-known", "licenses"];

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });
for (const f of readdirSync(root)) {
  if (f.endsWith(".html") && statSync(join(root, f)).isFile()) cpSync(join(root, f), join(dist, f));
}
for (const f of allowFiles) if (existsSync(join(root, f))) cpSync(join(root, f), join(dist, f));
for (const d of allowDirs) if (existsSync(join(root, d))) cpSync(join(root, d), join(dist, d), { recursive: true });
cpSync(join(root, "config/_headers"), join(dist, "_headers"));

const legal = {};
for (const [key, file] of [["terms", "terms.html"], ["licence", "licence.html"], ["privacy", "privacy.html"]]) {
  const bytes = readFileSync(join(dist, file));
  const id = /Document ID: (LZ-[A-Z]+-\d{4}-\d{2}-\d{2}(?:\.\d+)?)/.exec(bytes.toString("utf8"));
  if (!id) throw new Error(`No "Document ID: LZ-..." line found in ${file}`);
  legal[key] = { version: id[1], sha256: createHash("sha256").update(bytes).digest("hex"), path: "/" + file.replace(/\.html$/, "") };
}
mkdirSync(join(root, "src/generated"), { recursive: true });
writeFileSync(
  join(root, "src/generated/legal.js"),
  "// Generated by scripts/build-assets.mjs. Do not edit by hand.\n" +
    `export const LEGAL = ${JSON.stringify(legal, null, 2)};\n`
);
console.log("dist/ built; legal versions:", Object.values(legal).map((l) => l.version).join(", "));
